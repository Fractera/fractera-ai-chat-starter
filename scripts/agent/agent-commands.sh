#!/bin/bash
# МЕНЮ КОМАНД БОТА — НАШИ ТРИ ПОВЕРХ ТРЁХ ПЛАГИНА (шаг 126, 2026-09-05).
#
# 🔒 ЗАКАЗ ВЛАДЕЛЬЦА: «команда для переключения модели, сброса контекста или
# отображения количества израсходованных токенов в этой сессии очень
# понадобилась бы».
#
# 🔒 ПЛАГИН НЕ ПРАВИТСЯ, И ЭТО ГЛАВНОЕ РЕШЕНИЕ ЭТОГО ФАЙЛА. Официальный плагин
# каналов объявляет своё меню сам (`bot.api.setMyCommands` в его `server.ts`).
# Дописать туда наши команды — значит завести правку в чужом вендоренном коде:
# она живёт до первого обновления плагина и исчезает МОЛЧА, потому что новая
# версия ставится в СОСЕДНЮЮ папку (`0.0.8/`), а наша остаётся в старой.
# Здесь меню ставится ПОВЕРХ, отдельным вызовом того же API Telegram.
#
# 🔒 СПИСОК ПОЛНЫЙ, А НЕ ДОБАВОЧНЫЙ: `setMyCommands` ЗАМЕЩАЕТ меню целиком.
# Пошли мы только свои три — исчезли бы `/start`, `/help`, `/status` плагина, и
# человек лишился бы инструкции по привязке ровно тогда, когда она нужна.
#
# 🔒 ЗАПУСКАЕТСЯ ПОСЛЕ ПЛАГИНА, А НЕ ДО. Плагин ставит своё меню при старте
# канала; наш вызов обязан прийти следом, иначе его затрут. Пусковой файл зовёт
# этот скрипт с задержкой.
#
# 🛑 КОМАНДЫ ИСПОЛНЯЕТ АГЕНТ, А НЕ ЭТОТ СКРИПТ. Плагин пересылает всё, что не его
# собственная команда, в сессию как обычный текст — значит `/tokens` доедет до
# агента строкой, и что с ней делать, написано в его `CLAUDE.md`. Второго
# исполнителя команд мы не заводим: он разошёлся бы с агентом на первой правке.
set -u
export PATH=/usr/local/bin:/usr/bin:/bin

ENV_FILE=/root/.claude/channels/telegram/.env
T=$(grep -o 'TELEGRAM_BOT_TOKEN=.*' "$ENV_FILE" 2>/dev/null | cut -d= -f2- | tr -d '\r\n')
if [ -z "${T:-}" ]; then
  echo "токена нет — меню не ставится" >&2
  exit 1
fi

read -r -d '' CMDS <<'JSON'
[
  {"command":"start",  "description":"Приветствие и как привязать бота"},
  {"command":"help",   "description":"Что умеет этот бот"},
  {"command":"status", "description":"Состояние привязки"},
  {"command":"tokens", "description":"Сколько токенов израсходовано в этой сессии"},
  {"command":"reset",  "description":"Сбросить контекст — начать сессию заново"},
  {"command":"model",  "description":"Показать или сменить модель (например: /model opus)"}
]
JSON

# 🔒 ОБЛАСТЬ ВИДИМОСТИ ОБЯЗАТЕЛЬНА, И ЭТО ГЛАВНОЕ ЗДЕСЬ.
#
# ✗ ОПЛАЧЕНО ЖИВЬЁМ 2026-09-05: владелец открыл меню и увидел прежние три
# команды. Меню было поставлено — но в область `default`, а плагин ставит свои
# три в `all_private_chats`. У Telegram УЗКАЯ ОБЛАСТЬ ПЕРЕКРЫВАЕТ ШИРОКУЮ, и в
# личной переписке действовал список плагина. `getMyCommands` без области
# показывал наши шесть и выглядел доказательством — это была проверка не того,
# что видит человек.
# 🔒 ПРОВЕРЯТЬ НАДО ТУ ОБЛАСТЬ, В КОТОРОЙ ЧЕЛОВЕК СМОТРИТ, а не ту, в которую
# писали.
#
# 🔒 СТАВИМ В ОБЕ: `all_private_chats` — та, что действует и которую занял
# плагин; `default` — запасная, на случай если плагин однажды перестанет
# занимать первую.
FAIL=0
for SCOPE in '{"type":"all_private_chats"}' '{"type":"default"}'; do
  OUT=$(curl -s -m 15 -X POST "https://api.telegram.org/bot$T/setMyCommands"     -H 'content-type: application/json'     -d "{\"commands\":$CMDS,\"scope\":$SCOPE}")
  case "$OUT" in
    *'"ok":true'*) echo "меню обновлено в области $SCOPE" ;;
    *)             echo "Telegram отказал ($SCOPE): $OUT" >&2; FAIL=1 ;;
  esac
done
exit $FAIL
