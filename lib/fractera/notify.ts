import "server-only";

import postgres from "postgres";

// «В РАЗГОВОРЕ ЧТО-ТО ПОЯВИЛОСЬ» — ОДНА СТРОКА, КОТОРУЮ БАЗА ГОВОРИТ САМА (100-1).
//
// 🔒 ЗАКАЗ ВЛАДЕЛЬЦА ДОСЛОВНО 2026-09-03: «когда я пишу в Telegram, я ожидаю, что
// это практически сразу же появится в чате».
//
// 🛑 ТАЙМЕР НА ПЕРЕЗАГРУЗКУ СТРАНИЦЫ ОТВЕРГНУТ ИМ ЖЕ И МНОЙ. Он рвёт набранный
// текст, сбрасывает прокрутку, гасит идущий поток ответа и качает всю страницу
// ради одной строки.
//
// 🔒 БАЗА БУДИТ СЕРВЕР, А НЕ СЕРВЕР ОПРАШИВАЕТ БАЗУ. `NOTIFY` — родное средство
// Postgres: пишущий говорит один раз, слушающие узнают мгновенно. Опрос базы
// «не появилось ли чего» был бы вторым источником правды о том же — и стоил бы
// запроса в секунду на каждую открытую вкладку.
//
// 🔒 В СИГНАЛЕ ЕДЕТ ТОЛЬКО НОМЕР РАЗГОВОРА, А НЕ САМО СООБЩЕНИЕ. У `NOTIFY`
// предел полезной нагрузки около 8 КБ — длинное сообщение обрезалось бы, и
// обрезалось бы МОЛЧА. Получив номер, вкладка перечитывает разговор из
// единственного хранилища: тот же закон, по которому мы не заводим вторых
// источников.

/** Имя канала уведомлений. Одно на всё приложение — фильтрует уже слушающий. */
export const CHAT_CHANNEL = "fractera_chat_message";

/**
 * Сказать всем слушающим, что в разговоре появилось сообщение.
 *
 * 🔒 ОТКАЗ ЗДЕСЬ НЕ РОНЯЕТ ЗАПИСЬ. Сообщение уже в базе — это главное; не
 * доехавшее уведомление означает лишь, что вкладка увидит его при следующем
 * открытии. Обратный порядок (сначала сигнал, потом запись) обещал бы то, чего
 * ещё нет.
 */
export async function notifyChat(chatId: string, userId: string): Promise<void> {
  const url = process.env.POSTGRES_URL ?? "";
  if (!url) {
    return;
  }
  const client = postgres(url, { max: 1 });
  try {
    // 🔒 ХОЗЯИН ЕДЕТ В СИГНАЛЕ, И ЭТО ЗАЩИТА, А НЕ УДОБСТВО (100-2). Слушателю
    // нужно знать не только «что-то появилось», но и «у КОГО»: без этого он
    // либо спрашивал бы базу на каждое чужое уведомление, либо узнавал бы о
    // существовании чужих разговоров. Оба исхода плохи по-разному.
    await client.notify(CHAT_CHANNEL, JSON.stringify({ c: chatId, u: userId }));
  } catch {
    // Молча: уведомление — удобство, а не хранение.
  } finally {
    await client.end();
  }
}
