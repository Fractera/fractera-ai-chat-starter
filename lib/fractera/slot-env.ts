import "server-only";

import { readFileSync } from "node:fs";

// ОКРУЖЕНИЕ СЛОТА — ОДИН ЧИТАТЕЛЬ НА ВЕСЬ ЧАТ (97-2).
//
// 🔒 ЧАТ НЕ ДЕРЖИТ СВОИХ КОПИЙ ЧУЖИХ СЕКРЕТОВ. Ключ модели, адрес слоя данных и
// секрет канала живут в `.env.local` проекта, и читаются оттуда на каждом
// запросе. Своя копия расходится с оригиналом молча — в тот день, когда владелец
// поменяет значение в одном месте из двух.
//
// 🔒 ФУНКЦИЯ ВЫНЕСЕНА СЮДА, ПОТОМУ ЧТО ПОТРЕБИТЕЛЕЙ СТАЛО ДВА. Она жила внутри
// `media.ts`; второй потребитель означал бы вторую копию — ровно тот дефект, от
// которого этот файл и защищает. Тот же закон, что у ленты сообщений: способность,
// у которой нет хозяина, переписывается каждым, кому она понадобилась.

/** Значение ключа из `.env.local` проекта. Пусто — ключа нет или файл недоступен. */
export function slotEnv(key: string): string {
  const path = process.env.FRACTERA_SLOT_ENV || "/opt/fractera/app/.env.local";
  try {
    const raw = readFileSync(path, "utf8");
    return (raw.match(new RegExp(`^${key}=(.+)$`, "m")) ?? [])[1]?.trim() ?? "";
  } catch {
    // 🔒 ОТСУТСТВИЕ ФАЙЛА — ЗАКОННОЕ СОСТОЯНИЕ, А НЕ ПОЛОМКА. На машине
    // разработчика слота нет вовсе, и чат обязан работать: значение придёт из
    // собственного окружения процесса.
    return "";
  }
}
