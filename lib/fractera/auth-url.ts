// ✗ ОПЛАЧЕНО ВЛАДЕЛЬЦЕМ ЖИВЬЁМ: кнопка «войти» на странице приветствия вела на
// `http://213.199.61.7:3001/login` — голый IP по НЕЗАЩИЩЁННОМУ http, где
// авторизации нет вовсе. Дословно: «мы уже переехали на защищённый маршрут, а
// ссылка отправляет нас на незащищённый».
//
// 🛑 ПРИЧИНА НЕ В ОПЕЧАТКЕ, А В ЗАПЕКАНИИ. `NEXT_PUBLIC_AUTH_URL` попадает в
// сборку и застывает: значение записано при рождении сервера, когда домена ещё
// не было. Подключив домен, человек обязан был бы вспомнить про пересборку чата
// — а он не обязан этого знать. Сервер, где домен появился позже, получал бы
// сломанный вход МОЛЧА.
//
// 🔒 ДВА МЕСТА СЧИТАЛИ ЭТОТ АДРЕС ПО ОТДЕЛЬНОСТИ — страница приветствия (вход) и
// раскладка чата (выход). Две сборки одного адреса расходятся на первой правке,
// и расходятся так, что одна половина работает: заметить это можно только
// нажав обе кнопки.

/**
 * Куда браузер идёт входить и выходить.
 *
 * 🔒 ВЫВОДИТСЯ ИЗ ХОСТА, ПО КОТОРОМУ ОТКРЫТ САМ ЧАТ. `chat.<домен>` и
 * `auth.<домен>` — соседи по одному списку `SUBDOMAINS` панели: оттуда берутся и
 * блоки nginx, и имена в сертификате. Значит приставка заменяется, а не
 * угадывается.
 *
 * 🔒 ПЕРЕМЕННАЯ ОСТАЁТСЯ ЗАПАСНЫМ ПУТЁМ — для машины без домена (режим по IP) и
 * для разработки, где хост не начинается с `chat.`.
 */
export function publicAuthUrl(host: string, proto: string): string {
  const fromHost = host.startsWith("chat.")
    ? `${proto}://auth.${host.slice("chat.".length)}`
    : "";
  return (
    fromHost ||
    process.env.NEXT_PUBLIC_AUTH_URL ||
    process.env.AUTH_SERVICE_URL ||
    ""
  );
}
