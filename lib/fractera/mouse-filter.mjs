// ✗ ЧЕМ ОПЛАЧЕН. Владелец подключился кнопкой «Сессия агента» к живому
// полноэкранному `claude` — и любое движение курсора над терминалом стало
// печатать в поле ввода агента поток вида `84;25M86;25M89;24M94;24M102;...`.
// Это отчёты мыши SGR (`ESC [ < кнопка ; x ; y M`), у которых голова съедена по
// дороге, а хвост доехал до приложения как набранный текст.
//
// 🛑 МЕХАНИЗМ, И ОН НЕ ТОТ, ЧТО ЛЕЧИЛИ В 114-7. Там терминал оставался отравлен
// ПОСЛЕ обрыва TUI, и лечение — вернуть режимы при закрытии сокета. Здесь TUI
// ЖИВ и включает слежение за мышью намеренно: `claude` объявляет `?1000h ?1002h
// ?1003h ?1006h`, xterm.js честно начинает слать координаты, а между ними и
// приложением стоит `screen`, который эти отчёты до `claude` в целости не
// доносит. Гасить режимы после включения бесполезно — приложение включает их
// снова на каждой перерисовке.
//
// 🔒 ПОЭТОМУ ЛЕЧЕНИЕ НА ВХОДЕ, А НЕ НА ВЫХОДЕ: xterm.js просто не узнаёт, что
// мышь включена. Не зная этого, он не отправляет ни одного отчёта — источник
// мусора исчезает, а не заглушается.
//
// 🔒 ВЫРЕЗАЕТСЯ РОВНО СЛЕЖЕНИЕ ЗА МЫШЬЮ И НИЧЕГО БОЛЬШЕ. `?1049h`
// (дополнительный экран) и `?2004h` (скобочная вставка) обязаны дойти: без
// первого полноэкранный интерфейс поедет по ленте, без второго вставка текста
// потеряет границы. Составная форма `ESC [ ? 1000;1002;1006 h` разбирается по
// числам: мышиные убираются, соседи остаются в своей последовательности.
//
// 🛑 ЦЕНА НАЗВАНА: мышью в интерфейсе агента пользоваться нельзя — ни кликнуть
// по пункту, ни прокрутить колесом. Клавиатура работает целиком, прокрутка —
// `PgUp`/`PgDn` (в `screen` — `Ctrl+A`, затем `[`). Мусор в поле ввода дороже
// мыши: он портит команду, которую человек набирает, и уходит агенту как текст.

const ESC = String.fromCharCode(27);

/**
 * Режимы DEC, включающие отчёты мыши.
 *
 * 1000 — клики · 1001 — highlight · 1002 — с протяжкой · 1003 — любое движение
 * 1004 — фокус окна · 1005 — utf8-координаты · 1006 — SGR · 1015 — urxvt
 * 1016 — SGR-pixels.
 *
 * 🔒 1004 ВКЛЮЧЁН В СПИСОК НАМЕРЕННО: отчёты фокуса (`ESC [ I` / `ESC [ O`)
 * приходят от переключения вкладки браузера и попадают в ввод тем же путём.
 */
const MOUSE_MODES = new Set(['1000', '1001', '1002', '1003', '1004', '1005', '1006', '1015', '1016']);

/** Максимальный хвост, который имеет смысл придержать: `ESC [ ? 1000;1002;1006 h`. */
const MAX_TAIL = 32;

/**
 * Создаёт фильтр с памятью между кусками.
 *
 * 🔒 ПАМЯТЬ ОБЯЗАТЕЛЬНА: поток PTY приезжает произвольными кусками, и
 * последовательность рвётся пополам между двумя сообщениями сокета. Фильтр без
 * памяти пропустил бы половинку `ESC [ ?100` и включил бы мышь на следующем
 * куске — то есть работал бы через раз, а выглядел бы рабочим.
 */
export function createMouseFilter() {
  let tail = '';

  return function filter(chunk) {
    const data = tail + String(chunk);
    tail = '';

    // Незавершённая последовательность в самом конце придерживается до
    // следующего куска. Ищем последний ESC и смотрим, закрыт ли он.
    const lastEsc = data.lastIndexOf(ESC);
    let body = data;
    if (lastEsc >= 0 && data.length - lastEsc <= MAX_TAIL) {
      const rest = data.slice(lastEsc);
      // Закрытой считаем последовательность с финальной буквой после `ESC [ ? …`
      // либо любую, которая уже не может оказаться режимом DEC.
      if (/^\x1b\[\??[\d;]*$/.test(rest)) {
        body = data.slice(0, lastEsc);
        tail = rest;
      }
    }

    return body.replace(/\x1b\[\?([\d;]+)([hl])/g, (whole, nums, verb) => {
      if (verb !== 'h') return whole; // выключение не мешает никому
      const kept = nums.split(';').filter(n => !MOUSE_MODES.has(n));
      if (kept.length === nums.split(';').length) return whole; // мыши нет — не трогаем
      return kept.length ? ESC + '[?' + kept.join(';') + 'h' : '';
    });
  };
}

/**
 * Последовательность, гасящая уже включённое слежение.
 *
 * 🔒 НУЖНА ВМЕСТЕ С ФИЛЬТРОМ, А НЕ ВМЕСТО НЕГО. Фильтр не даёт включить мышь
 * ВПЕРЁД; эта строка убирает то, что успело включиться до него — например, в
 * сессии, открытой прошлой версией страницы.
 */
export const MOUSE_OFF = ['?1000l', '?1002l', '?1003l', '?1004l', '?1005l', '?1006l', '?1015l', '?1016l']
  .map(m => ESC + '[' + m)
  .join('');
