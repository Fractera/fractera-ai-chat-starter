/**
 * Два режима, названные владельцем.
 *
 * 🔒 ИМЯ РЕЖИМА — `claude`, А НЕ `cloud`. Поправка владельца 2026-09-04: «Cloud
 * Agent SDK incorrect», с адресом первоисточника
 * `https://code.claude.com/docs/en/agent-sdk/overview`. Продукт называется
 * **Claude Agent SDK**; «Cloud» — артефакт распознавания речи.
 */
export const AUTOMATION_MODES = ["claude", "openai"] as const;
export type AutomationMode = (typeof AUTOMATION_MODES)[number];

export function isAutomationMode(v: unknown): v is AutomationMode {
  return typeof v === "string" && (AUTOMATION_MODES as readonly string[]).includes(v);
}

/**
 * Действующий режим.
 *
 * 🔒 УМОЛЧАНИЕ — `claude`, ПРЯМОЕ СЛОВО ВЛАДЕЛЬЦА: «по умолчанию показываем
 * переключатель в состоянии режим Claude агент SDK активен». Умолчание обязано
 * совпадать с читателем на экране архитектора один в один — иначе две
 * поверхности назовут ненастроенный проект по-разному.
 */
export function automationModeOf(config: Record<string, unknown>): AutomationMode {
  return isAutomationMode(config.automationMode) ? config.automationMode : "claude";
}

/** Путь к `PLATFORM-CONFIG` слота. Переопределяется окружением — как у `slotEnv`. */
function platformConfigPath(): string {
  return (
    process.env.FRACTERA_SLOT_PLATFORM_CONFIG ||
    "/opt/fractera/app/PLATFORM-CONFIG/platform-config.json"
  );
}

/**
 * Сырое содержимое конфига слота.
 *
 * 🔒 СЫРОЕ, БЕЗ УМОЛЧАНИЙ, И РАЗНИЦА СОДЕРЖАТЕЛЬНАЯ: по слитому с умолчаниями
 * «режим не выбирали» неотличимо от «выбрали Claude». Тот же приём, что у
 * `readRawPlatformConfig()` на экране архитектора.
 *
 * 🛑 ОТСУТСТВИЕ ФАЙЛА — ЗАКОННОЕ СОСТОЯНИЕ, А НЕ ПОЛОМКА: на машине разработчика
 * слота нет вовсе, и чат обязан работать. Пустой объект означает «ничего не
 * выбирали», то есть действует умолчание.
 */
export function readSlotPlatformConfig(): Record<string, unknown> {
  try {
    const parsed: unknown = JSON.parse(readFileSync(platformConfigPath(), "utf8"));
    return typeof parsed === "object" && parsed !== null && !Array.isArray(parsed)
      ? (parsed as Record<string, unknown>)
      : {};
  } catch {
    return {};
  }
}

/** Режим, действующий сейчас, прочитанный с диска. */
export function currentAutomationMode(): AutomationMode {
  return automationModeOf(readSlotPlatformConfig());
}
